-- Documenti (da _ORG_PREFIX_Doc).
CREATE TABLE IF NOT EXISTS Doc (
	DocID INTEGER PRIMARY KEY,
	DocFUID TEXT NOT NULL,
	DocPID INTEGER NOT NULL,
	DocVID INTEGER NOT NULL,
	DocFname TEXT NOT NULL,
	DocExt TEXT NOT NULL,
	DocFType TEXT NOT NULL DEFAULT '',
	DocFSize INTEGER NOT NULL,
	DocUploadedOn TEXT NOT NULL,
	DocUploadedBy INTEGER NOT NULL,
	DocHash TEXT,
	DocViews INTEGER NOT NULL,
	DocDeleted INTEGER NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_Doc_fuid ON Doc (DocFUID);
CREATE INDEX IF NOT EXISTS idx_Doc_pid_vid_deleted ON Doc (DocPID, DocVID, DocDeleted);
